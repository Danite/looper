use crate::infra::dockerfile::PACKAGE_TO_BINARIES;
use crate::types::{Category, ShadowDep};
use std::collections::BTreeSet;
use std::fmt::Write;
use std::path::Path;

const BASE_IMAGE_MARKERS: &[(&str, &str)] = &[
    ("package.json", "node:20-slim"),
    ("requirements.txt", "python:3.12-slim"),
    ("pyproject.toml", "python:3.12-slim"),
    ("go.mod", "golang:1.23-alpine"),
    ("Cargo.toml", "rust:1.82-slim"),
    ("Gemfile", "ruby:3.3-slim"),
    ("composer.json", "php:8.3-cli"),
];

/// Generate a Dockerfile from Binary and Port shadow deps.
pub fn generate_dockerfile(deps: &[ShadowDep], project_root: &Path) -> String {
    let mut packages: BTreeSet<String> = BTreeSet::new();
    let mut unresolved: BTreeSet<String> = BTreeSet::new();
    let mut expose_ports: BTreeSet<u16> = BTreeSet::new();

    for dep in deps {
        match dep.category {
            Category::Binary => match resolve_package(&dep.name) {
                Some(pkg) => {
                    packages.insert(pkg.to_string());
                }
                None => {
                    unresolved.insert(dep.name.clone());
                }
            },
            Category::Port => {
                let direction = dep.metadata.get_str("direction").unwrap_or("");
                if direction == "listen" {
                    if let Some(port) = dep
                        .name
                        .strip_prefix(':')
                        .and_then(|s| s.parse::<u16>().ok())
                    {
                        expose_ports.insert(port);
                    }
                }
            }
            _ => {}
        }
    }

    if packages.is_empty() && unresolved.is_empty() && expose_ports.is_empty() {
        return String::from("# No Dockerfile content detected by looper\n");
    }

    let base_image = detect_base_image(project_root);

    let mut out = String::new();
    writeln!(out, "# Generated by looper — review before use\n").unwrap();
    writeln!(out, "FROM {base_image}\n").unwrap();
    writeln!(out, "WORKDIR /app").unwrap();

    if !packages.is_empty() {
        writeln!(out).unwrap();
        writeln!(
            out,
            "RUN apt-get update && apt-get install -y --no-install-recommends \\"
        )
        .unwrap();
        for pkg in &packages {
            writeln!(out, "    {pkg} \\").unwrap();
        }
        writeln!(out, " && rm -rf /var/lib/apt/lists/*").unwrap();
    }

    if !unresolved.is_empty() {
        writeln!(out).unwrap();
        writeln!(
            out,
            "# TODO: The following binaries were detected but have no known package mapping."
        )
        .unwrap();
        writeln!(
            out,
            "# Install them manually or add to the RUN command above."
        )
        .unwrap();
        for name in &unresolved {
            writeln!(out, "# - {name}").unwrap();
        }
    }

    writeln!(out).unwrap();
    writeln!(out, "COPY . .").unwrap();

    if !expose_ports.is_empty() {
        writeln!(out).unwrap();
        for port in &expose_ports {
            writeln!(out, "EXPOSE {port}").unwrap();
        }
    }

    writeln!(out).unwrap();
    writeln!(out, "# CMD [\"your-start-command\"]").unwrap();

    out
}

fn resolve_package(binary: &str) -> Option<&'static str> {
    for (pkg, bins) in PACKAGE_TO_BINARIES {
        if bins.contains(&binary) {
            return Some(pkg);
        }
    }
    None
}

fn detect_base_image(project_root: &Path) -> &'static str {
    for (marker, image) in BASE_IMAGE_MARKERS {
        if project_root.join(marker).exists() {
            return image;
        }
    }
    "debian:bookworm-slim"
}
