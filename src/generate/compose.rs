use crate::types::{Category, ShadowDep};
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;

struct ServiceTemplate {
    protocol: &'static str,
    name: &'static str,
    image: &'static str,
    port: u16,
    env_vars: &'static [(&'static str, &'static str)],
}

const PROTOCOL_TO_SERVICE: &[ServiceTemplate] = &[
    ServiceTemplate { protocol: "redis", name: "redis", image: "redis:7", port: 6379, env_vars: &[] },
    ServiceTemplate { protocol: "postgres", name: "db", image: "postgres:16", port: 5432, env_vars: &[
        ("POSTGRES_PASSWORD", "postgres"),
        ("POSTGRES_DB", "app"),
    ]},
    ServiceTemplate { protocol: "mongodb", name: "mongo", image: "mongo:7", port: 27017, env_vars: &[] },
    ServiceTemplate { protocol: "mysql", name: "mysql", image: "mysql:8", port: 3306, env_vars: &[
        ("MYSQL_ROOT_PASSWORD", "mysql"),
        ("MYSQL_DATABASE", "app"),
    ]},
    ServiceTemplate { protocol: "amqp", name: "rabbitmq", image: "rabbitmq:3-management", port: 5672, env_vars: &[] },
    ServiceTemplate { protocol: "nats", name: "nats", image: "nats:2", port: 4222, env_vars: &[] },
    ServiceTemplate { protocol: "memcached", name: "memcached", image: "memcached:1", port: 11211, env_vars: &[] },
    ServiceTemplate { protocol: "elasticsearch", name: "elasticsearch", image: "elasticsearch:8", port: 9200, env_vars: &[
        ("discovery.type", "single-node"),
    ]},
    ServiceTemplate { protocol: "s3", name: "minio", image: "minio/minio:latest", port: 9000, env_vars: &[
        ("MINIO_ROOT_USER", "minioadmin"),
        ("MINIO_ROOT_PASSWORD", "minioadmin"),
    ]},
];

struct ComposeService {
    name: String,
    image: String,
    port: u16,
    env_vars: Vec<(String, String)>,
}

/// Generate a docker-compose.yml from Port and EnvVar shadow deps.
pub fn generate_compose(deps: &[ShadowDep]) -> String {
    let mut services: BTreeMap<String, ComposeService> = BTreeMap::new();
    let mut app_ports: BTreeSet<u16> = BTreeSet::new();
    let mut app_env_vars: Vec<String> = Vec::new();

    for dep in deps {
        match dep.category {
            Category::Port => {
                let direction = dep.metadata.get_str("direction").unwrap_or("connect");
                let protocol_hint = dep.metadata.get_str("protocol_hint").unwrap_or("");
                let port = extract_port(&dep.name);

                if direction == "listen" {
                    if let Some(p) = port {
                        app_ports.insert(p);
                    }
                } else if direction == "connect" {
                    if let Some(svc_def) = lookup_service(protocol_hint) {
                        services.entry(svc_def.name.clone()).or_insert(svc_def);
                    }
                }
            }
            Category::EnvVar => {
                if !app_env_vars.contains(&dep.name) {
                    app_env_vars.push(dep.name.clone());
                }
            }
            _ => {}
        }
    }

    if services.is_empty() && app_ports.is_empty() && app_env_vars.is_empty() {
        return String::from("# No services detected by looper\n");
    }

    let mut out = String::new();
    writeln!(out, "# Generated by looper — review before use\n").unwrap();

    // serde_yaml adds unwanted formatting; hand-build for clean output
    writeln!(out, "services:").unwrap();

    // App service
    if !app_ports.is_empty() || !app_env_vars.is_empty() {
        writeln!(out, "  app:").unwrap();
        writeln!(out, "    build: .").unwrap();

        if !app_ports.is_empty() {
            writeln!(out, "    ports:").unwrap();
            for port in &app_ports {
                writeln!(out, "      - \"{port}:{port}\"").unwrap();
            }
        }

        if !app_env_vars.is_empty() {
            writeln!(out, "    environment:").unwrap();
            for name in &app_env_vars {
                writeln!(out, "      - {name}").unwrap();
            }
        }

        let svc_names: Vec<&str> = services.keys().map(|s| s.as_str()).collect();
        if !svc_names.is_empty() {
            writeln!(out, "    depends_on:").unwrap();
            for name in &svc_names {
                writeln!(out, "      - {name}").unwrap();
            }
        }
    }

    // Infrastructure services
    for svc in services.values() {
        writeln!(out).unwrap();
        writeln!(out, "  {}:", svc.name).unwrap();
        writeln!(out, "    image: {}", svc.image).unwrap();
        writeln!(out, "    ports:").unwrap();
        writeln!(out, "      - \"{}:{}\"", svc.port, svc.port).unwrap();

        if !svc.env_vars.is_empty() {
            writeln!(out, "    environment:").unwrap();
            for (key, val) in &svc.env_vars {
                writeln!(out, "      {key}: {val}").unwrap();
            }
        }
    }

    out
}

fn lookup_service(protocol_hint: &str) -> Option<ComposeService> {
    for tmpl in PROTOCOL_TO_SERVICE {
        if tmpl.protocol == protocol_hint {
            return Some(ComposeService {
                name: tmpl.name.to_string(),
                image: tmpl.image.to_string(),
                port: tmpl.port,
                env_vars: tmpl.env_vars.iter().map(|(k, v)| (k.to_string(), v.to_string())).collect(),
            });
        }
    }
    None
}

fn extract_port(name: &str) -> Option<u16> {
    name.strip_prefix(':')?.parse().ok()
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::types::{Confidence, Location, Metadata};
    use serde_json::json;

    fn port_dep(port: u16, direction: &str, protocol_hint: &str) -> ShadowDep {
        let name = format!(":{port}");
        let id = format!("port::{port}::{direction}");
        let mut meta = Metadata::new();
        meta.insert("direction", json!(direction));
        if !protocol_hint.is_empty() {
            meta.insert("protocol_hint", json!(protocol_hint));
        }
        ShadowDep {
            id,
            category: Category::Port,
            name,
            confidence: Confidence::High,
            metadata: meta,
            locations: vec![Location::new("src/db.ts", 5, 1)],
        }
    }

    fn env_dep(name: &str) -> ShadowDep {
        let mut meta = Metadata::new();
        meta.insert("required", json!(true));
        ShadowDep::new(
            Category::EnvVar,
            name,
            Confidence::High,
            Location::new("src/config.ts", 10, 1),
        )
        .with_metadata(meta)
    }

    #[test]
    fn empty_deps_produces_header() {
        let result = generate_compose(&[]);
        assert!(result.contains("No services detected"));
    }

    #[test]
    fn redis_service_from_connect_port() {
        let deps = vec![port_dep(6379, "connect", "redis")];
        let result = generate_compose(&deps);
        assert!(result.contains("redis:"));
        assert!(result.contains("image: redis:7"));
        assert!(result.contains("\"6379:6379\""));
    }

    #[test]
    fn postgres_service_with_env() {
        let deps = vec![port_dep(5432, "connect", "postgres")];
        let result = generate_compose(&deps);
        assert!(result.contains("image: postgres:16"));
        assert!(result.contains("POSTGRES_PASSWORD"));
    }

    #[test]
    fn listen_port_goes_to_app_service() {
        let deps = vec![port_dep(3000, "listen", "http")];
        let result = generate_compose(&deps);
        assert!(result.contains("app:"));
        assert!(result.contains("\"3000:3000\""));
        assert!(!result.contains("image: http"));
    }

    #[test]
    fn env_vars_in_app_service() {
        let deps = vec![env_dep("DATABASE_URL"), env_dep("API_KEY")];
        let result = generate_compose(&deps);
        assert!(result.contains("app:"));
        assert!(result.contains("DATABASE_URL"));
        assert!(result.contains("API_KEY"));
    }

    #[test]
    fn app_depends_on_infra_services() {
        let deps = vec![
            port_dep(3000, "listen", "http"),
            port_dep(5432, "connect", "postgres"),
            port_dep(6379, "connect", "redis"),
        ];
        let result = generate_compose(&deps);
        assert!(result.contains("depends_on:"));
        assert!(result.contains("- db"));
        assert!(result.contains("- redis"));
    }

    #[test]
    fn deduplicates_same_protocol() {
        let deps = vec![
            port_dep(5432, "connect", "postgres"),
            port_dep(5432, "connect", "postgres"),
        ];
        let result = generate_compose(&deps);
        let count = result.matches("image: postgres:16").count();
        assert_eq!(count, 1);
    }

    #[test]
    fn unknown_protocol_ignored() {
        let deps = vec![port_dep(9999, "connect", "unknown_proto")];
        let result = generate_compose(&deps);
        assert!(result.contains("No services detected"));
    }

    #[test]
    fn non_port_non_env_deps_ignored() {
        let binary_dep = ShadowDep::new(
            Category::Binary,
            "ffmpeg",
            Confidence::High,
            Location::new("src/video.ts", 5, 1),
        );
        let deps = vec![binary_dep];
        let result = generate_compose(&deps);
        assert!(result.contains("No services detected"));
    }

    #[test]
    fn services_sorted_by_name() {
        let deps = vec![
            port_dep(6379, "connect", "redis"),
            port_dep(5432, "connect", "postgres"),
        ];
        let result = generate_compose(&deps);
        let db_pos = result.find("  db:").unwrap();
        let redis_pos = result.find("  redis:").unwrap();
        assert!(db_pos < redis_pos);
    }
}
