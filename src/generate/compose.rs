struct ComposeService {
    name: String,
    image: String,
    port: u16,
    env_vars: Vec<(String, String)>,
}

/// Generate a docker-compose.yml from Port and EnvVar shadow deps.
pub fn generate_compose(deps: &[ShadowDep]) -> String {
    let mut services: BTreeMap<String, ComposeService> = BTreeMap::new();
    let mut app_ports: BTreeSet<u16> = BTreeSet::new();
    let mut app_env_vars: Vec<String> = Vec::new();

    for dep in deps {
        match dep.category {
            Category::Port => {
                let direction = dep.metadata.get_str("direction").unwrap_or("connect");
                let protocol_hint = dep.metadata.get_str("protocol_hint").unwrap_or("");
                let port = extract_port(&dep.name);

                if direction == "listen" {
                    if let Some(p) = port {
                        app_ports.insert(p);
                    }
                } else if direction == "connect" {
                    if let Some(svc_def) = lookup_service(protocol_hint) {
                        services.entry(svc_def.name.clone()).or_insert(svc_def);
                    }
                }
            }
            Category::EnvVar => {
                if !app_env_vars.contains(&dep.name) {
                    app_env_vars.push(dep.name.clone());
                }
            }
            _ => {}
        }
    }

    if services.is_empty() && app_ports.is_empty() && app_env_vars.is_empty() {
        return String::from("# No services detected by looper\n");
    }

    let mut out = String::new();
    writeln!(out, "# Generated by looper — review before use\n").unwrap();

    // serde_yaml adds unwanted formatting; hand-build for clean output
    writeln!(out, "services:").unwrap();

    // App service
    if !app_ports.is_empty() || !app_env_vars.is_empty() {
        writeln!(out, "  app:").unwrap();
        writeln!(out, "    build: .").unwrap();

        if !app_ports.is_empty() {
            writeln!(out, "    ports:").unwrap();
            for port in &app_ports {
                writeln!(out, "      - \"{port}:{port}\"").unwrap();
            }
        }

        if !app_env_vars.is_empty() {
            writeln!(out, "    environment:").unwrap();
            for name in &app_env_vars {
                writeln!(out, "      - {name}").unwrap();
            }
        }

        let svc_names: Vec<&str> = services.keys().map(|s| s.as_str()).collect();
        if !svc_names.is_empty() {
            writeln!(out, "    depends_on:").unwrap();
            for name in &svc_names {
                writeln!(out, "      - {name}").unwrap();
            }
        }
    }

    // Infrastructure services
    for svc in services.values() {
        writeln!(out).unwrap();
        writeln!(out, "  {}:", svc.name).unwrap();
        writeln!(out, "    image: {}", svc.image).unwrap();
        writeln!(out, "    ports:").unwrap();
        writeln!(out, "      - \"{}:{}\"", svc.port, svc.port).unwrap();

        if !svc.env_vars.is_empty() {
            writeln!(out, "    environment:").unwrap();
            for (key, val) in &svc.env_vars {
                writeln!(out, "      {key}: {val}").unwrap();
            }
        }
    }

    out
}

fn lookup_service(protocol_hint: &str) -> Option<ComposeService> {
    for tmpl in PROTOCOL_TO_SERVICE {
        if tmpl.protocol == protocol_hint {
            return Some(ComposeService {
                name: tmpl.name.to_string(),
                image: tmpl.image.to_string(),
                port: tmpl.port,
                env_vars: tmpl
                    .env_vars
                    .iter()
                    .map(|(k, v)| (k.to_string(), v.to_string()))
                    .collect(),
            });
        }
    }
    None
}

fn extract_port(name: &str) -> Option<u16> {
    name.strip_prefix(':')?.parse().ok()
}
