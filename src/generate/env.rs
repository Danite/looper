use crate::types::{Category, ShadowDep};
use std::fmt::Write;

/// Generate a .env.example file from EnvVar shadow deps.
pub fn generate_env(deps: &[ShadowDep]) -> String {
    let env_deps: Vec<&ShadowDep> = deps
        .iter()
        .filter(|d| d.category == Category::EnvVar)
        .collect();

    if env_deps.is_empty() {
        return String::from("# No environment variables detected by looper\n");
    }

    let required: Vec<&&ShadowDep> = env_deps.iter().filter(|d| is_required(d)).collect();
    let optional: Vec<&&ShadowDep> = env_deps.iter().filter(|d| !is_required(d)).collect();

    let mut out = String::new();
    writeln!(out, "# Generated by looper — https://github.com/example/looper").unwrap();
    writeln!(out, "# Review and fill in values before use.\n").unwrap();

    if !required.is_empty() {
        writeln!(out, "# ── Required ─────────────────────────────────────").unwrap();
        for dep in &required {
            write_env_entry(&mut out, dep, true);
        }
    }

    if !optional.is_empty() {
        if !required.is_empty() {
            writeln!(out).unwrap();
        }
        writeln!(out, "# ── Optional (have defaults) ─────────────────────").unwrap();
        for dep in &optional {
            write_env_entry(&mut out, dep, false);
        }
    }

    out
}

fn write_env_entry(out: &mut String, dep: &ShadowDep, required: bool) {
    let locations: Vec<String> = dep
        .locations
        .iter()
        .take(3)
        .map(|l| format!("{}:{}", l.file, l.line))
        .collect();
    let loc_str = locations.join(", ");
    writeln!(out, "# Used in: {loc_str}").unwrap();

    let default_value = dep.metadata.get_str("default_value");

    if required {
        let placeholder = infer_placeholder(&dep.name);
        writeln!(out, "{}={}", dep.name, placeholder).unwrap();
    } else {
        let val = default_value.unwrap_or("");
        writeln!(out, "{}={}", dep.name, val).unwrap();
    }
}

fn is_required(dep: &ShadowDep) -> bool {
    dep.metadata.get_bool("required").unwrap_or(true)
}

/// Infer a placeholder value from the env var name.
fn infer_placeholder(name: &str) -> &'static str {
    let upper = name.to_uppercase();

    if upper.ends_with("_URL") || upper.ends_with("_URI") {
        return "https://";
    }
    if upper.ends_with("_HOST") || upper.ends_with("_HOSTNAME") {
        return "localhost";
    }
    if upper.ends_with("_PORT") {
        return "0";
    }
    if upper.ends_with("_KEY") || upper.ends_with("_SECRET") || upper.ends_with("_TOKEN") {
        return "changeme";
    }
    if upper.ends_with("_PASSWORD") || upper.ends_with("_PASS") {
        return "changeme";
    }
    if upper.ends_with("_PATH") || upper.ends_with("_DIR") || upper.ends_with("_DIRECTORY") {
        return "./";
    }
    if upper.ends_with("_EMAIL") {
        return "user@example.com";
    }
    if upper == "NODE_ENV" {
        return "development";
    }
    if upper == "PORT" {
        return "3000";
    }
    if upper == "DEBUG" {
        return "false";
    }

    ""
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::types::{Confidence, Location, Metadata};
    use serde_json::json;

    fn env_dep(name: &str, required: bool, default_value: Option<&str>) -> ShadowDep {
        let mut meta = Metadata::new();
        meta.insert("required", json!(required));
        meta.insert("source_pattern", json!("direct_access"));
        if let Some(dv) = default_value {
            meta.insert("default_value", json!(dv));
        }
        ShadowDep::new(
            Category::EnvVar,
            name,
            Confidence::High,
            Location::new("src/config.ts", 10, 1),
        )
        .with_metadata(meta)
    }

    #[test]
    fn empty_deps_produces_header() {
        let result = generate_env(&[]);
        assert!(result.contains("No environment variables"));
    }

    #[test]
    fn required_var_uses_placeholder() {
        let deps = vec![env_dep("DATABASE_URL", true, None)];
        let result = generate_env(&deps);
        assert!(result.contains("DATABASE_URL=https://"));
        assert!(result.contains("Required"));
    }

    #[test]
    fn optional_var_uses_default() {
        let deps = vec![env_dep("PORT", false, Some("3000"))];
        let result = generate_env(&deps);
        assert!(result.contains("PORT=3000"));
        assert!(result.contains("Optional"));
    }

    #[test]
    fn groups_required_before_optional() {
        let deps = vec![
            env_dep("PORT", false, Some("3000")),
            env_dep("API_KEY", true, None),
        ];
        let result = generate_env(&deps);
        let req_pos = result.find("Required").unwrap();
        let opt_pos = result.find("Optional").unwrap();
        assert!(req_pos < opt_pos);
    }

    #[test]
    fn includes_location_comment() {
        let deps = vec![env_dep("FOO", true, None)];
        let result = generate_env(&deps);
        assert!(result.contains("src/config.ts:10"));
    }

    #[test]
    fn placeholder_for_secret() {
        assert_eq!(infer_placeholder("STRIPE_SECRET_KEY"), "changeme");
    }

    #[test]
    fn placeholder_for_host() {
        assert_eq!(infer_placeholder("REDIS_HOST"), "localhost");
    }

    #[test]
    fn placeholder_for_url() {
        assert_eq!(infer_placeholder("DATABASE_URL"), "https://");
    }

    #[test]
    fn placeholder_for_port() {
        assert_eq!(infer_placeholder("REDIS_PORT"), "0");
        assert_eq!(infer_placeholder("PORT"), "3000");
    }

    #[test]
    fn non_env_deps_are_ignored() {
        let binary_dep = ShadowDep::new(
            crate::types::Category::Binary,
            "ffmpeg",
            Confidence::High,
            Location::new("src/video.ts", 5, 1),
        );
        let deps = vec![binary_dep, env_dep("API_KEY", true, None)];
        let result = generate_env(&deps);
        assert!(!result.contains("ffmpeg"));
        assert!(result.contains("API_KEY"));
    }
}
